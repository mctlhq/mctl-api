package api

import (
	"context"
	"io"
	"log/slog"
	"net/http"
	"time"

	"github.com/mctlhq/mctl-api/internal/zitadelhook"
)

// Paths of the ZITADEL Actions v2 restCall targets (zitadelhook package).
const (
	zitadelHookIntentPath = "/api/v1/webhooks/zitadel/intent"
	zitadelHookCreatePath = "/api/v1/webhooks/zitadel/create-user"
	zitadelHookTokenPath  = "/api/v1/webhooks/zitadel/token-claims" //nolint:gosec // G101 matches "token" in a route path, not a credential
)

const maxZitadelHookBytes = 1 << 20 // 1 MiB

// ZitadelHookOptions wires the identity hook. Each target has its own
// signing key, generated by ZITADEL when the target is created; an empty
// key list rejects every call to that target.
type ZitadelHookOptions struct {
	Hook       *zitadelhook.Hook
	IntentKeys []string
	CreateKeys []string
	TokenKeys  []string
}

func (h *Handlers) zitadelHookHandler(keys func(*ZitadelHookOptions) []string, run func(*zitadelhook.Hook, context.Context, []byte) zitadelhook.Result, name string) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		opts := h.opts.ZitadelHook
		if opts == nil || opts.Hook == nil {
			writeError(w, http.StatusServiceUnavailable, "identity hook not configured")
			return
		}
		body, err := io.ReadAll(io.LimitReader(r.Body, maxZitadelHookBytes+1))
		if err != nil {
			writeError(w, http.StatusBadRequest, "failed to read body")
			return
		}
		if len(body) > maxZitadelHookBytes {
			writeError(w, http.StatusRequestEntityTooLarge, "payload too large")
			return
		}
		if err := zitadelhook.VerifySignature(body, r.Header.Get(zitadelhook.SignatureHeader), keys(opts), time.Now()); err != nil {
			slog.Warn("zitadel hook: signature rejected", "target", name, "error", err)
			writeError(w, http.StatusUnauthorized, "invalid signature")
			return
		}
		res := run(opts.Hook, r.Context(), body)
		slog.Info("zitadel hook", "target", name, "status", res.Status, "reason", res.Reason)
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(res.Status)
		_, _ = w.Write(res.Body)
	}
}

// HandleZitadelIntent is the RetrieveIdentityProviderIntent response target.
func (h *Handlers) HandleZitadelIntent(w http.ResponseWriter, r *http.Request) {
	h.zitadelHookHandler(func(o *ZitadelHookOptions) []string { return o.IntentKeys },
		(*zitadelhook.Hook).Intent, "intent")(w, r)
}

// HandleZitadelCreateUser is the request target on user-creating methods.
func (h *Handlers) HandleZitadelCreateUser(w http.ResponseWriter, r *http.Request) {
	h.zitadelHookHandler(func(o *ZitadelHookOptions) []string { return o.CreateKeys },
		(*zitadelhook.Hook).CreateGate, "create-user")(w, r)
}

// HandleZitadelTokenClaims is the preuserinfo / preaccesstoken target.
func (h *Handlers) HandleZitadelTokenClaims(w http.ResponseWriter, r *http.Request) {
	h.zitadelHookHandler(func(o *ZitadelHookOptions) []string { return o.TokenKeys },
		(*zitadelhook.Hook).TokenClaims, "token-claims")(w, r)
}
